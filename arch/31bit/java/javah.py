#!/usr/bin/env python3
# javah -- a JNI header generator for building GNU Classpath with a JDK that
# no longer has javah (JDK 10+).  VM/370plus 9.34.  Usage as Classpath's
# include/Makefile calls it:  javah -jni -bootclasspath DIR:ZIP -o OUT CLASS
# Reads the compiled class (directory or zip), writes the header javah did:
# static final integer constants as #defines, one prototype per native
# method (long names for overloaded natives).
import struct, sys, zipfile, os

def mangle(s):
    out = []
    for ch in s:
        if ch == '/' or ch == '.': out.append('_')
        elif ch == '_': out.append('_1')
        elif ch == ';': out.append('_2')
        elif ch == '[': out.append('_3')
        elif ch.isalnum() and ord(ch) < 128: out.append(ch)
        else: out.append('_0%04x' % ord(ch))
    return ''.join(out)

def load(cp, name):
    rel = name.replace('.', '/') + '.class'
    for p in cp:
        if os.path.isdir(p):
            f = os.path.join(p, rel)
            if os.path.exists(f): return open(f, 'rb').read()
        elif os.path.isfile(p) and p.endswith('.zip') or p.endswith('.jar'):
            try:
                with zipfile.ZipFile(p) as z: return z.read(rel)
            except (KeyError, FileNotFoundError, zipfile.BadZipFile): pass
    sys.exit('javah: class not found: ' + name)

def parse(b):
    p = 10; n = struct.unpack('>H', b[8:10])[0]; cp = [None] * n; i = 1
    while i < n:
        t = b[p]
        if t == 1:
            l = struct.unpack('>H', b[p+1:p+3])[0]
            cp[i] = ('utf8', b[p+3:p+3+l].decode('utf-8', 'replace')); p += 3 + l
        elif t in (3, 4):
            cp[i] = ('int' if t == 3 else 'float', b[p+1:p+5]); p += 5
        elif t in (5, 6):
            cp[i] = ('long' if t == 5 else 'double', b[p+1:p+9]); p += 9; i += 1
        elif t in (7, 8, 16, 19, 20):
            cp[i] = ('ref', struct.unpack('>H', b[p+1:p+3])[0]); p += 3
        elif t == 15: p += 4
        elif t in (9, 10, 11, 12, 17, 18): p += 5
        else: sys.exit('javah: bad constant tag %d' % t)
        i += 1
    p += 6
    ni = struct.unpack('>H', b[p:p+2])[0]; p += 2 + 2 * ni
    def members():
        nonlocal p
        cnt = struct.unpack('>H', b[p:p+2])[0]; p += 2; res = []
        for _ in range(cnt):
            acc, nm, ds, na = struct.unpack('>HHHH', b[p:p+8]); p += 8; cv = None
            for _ in range(na):
                an, al = struct.unpack('>HI', b[p:p+6])
                if cp[an][1] == 'ConstantValue':
                    cv = cp[struct.unpack('>H', b[p+6:p+8])[0]]
                p += 6 + al
            res.append((acc, cp[nm][1], cp[ds][1], cv))
        return res
    return members(), members()

JT = {'Z': 'jboolean', 'B': 'jbyte', 'C': 'jchar', 'S': 'jshort', 'I': 'jint',
      'J': 'jlong', 'F': 'jfloat', 'D': 'jdouble', 'V': 'void'}

def args(desc):
    res = []; i = 1
    while desc[i] != ')':
        j = i
        while desc[j] == '[': j += 1
        if desc[j] == 'L': j = desc.index(';', j)
        res.append(desc[i:j+1]); i = j + 1
    return res, desc[i+1:]

def ctype(t):
    if t in JT: return JT[t]
    if t[0] == '[':
        return (JT[t[1]] + 'Array') if len(t) == 2 and t[1] in JT and t[1] != 'V' else 'jobjectArray'
    return {'Ljava/lang/String;': 'jstring', 'Ljava/lang/Class;': 'jclass',
            'Ljava/lang/Throwable;': 'jthrowable'}.get(t, 'jobject')

def main():
    a = sys.argv[1:]; cp = []; out = None; classes = []
    while a:
        x = a.pop(0)
        if x in ('-jni', '-force', '-verbose'): continue
        if x in ('-bootclasspath', '-classpath', '-cp'): cp += a.pop(0).split(':'); continue
        if x == '-o': out = a.pop(0); continue
        if x == '-d': a.pop(0); continue
        classes.append(x)
    for c in classes:
        fields, methods = parse(load(cp, c))
        cm = mangle(c)
        L = ['/* DO NOT EDIT THIS FILE - it is machine generated */',
             '#include <jni.h>', '', '#ifndef __%s__' % cm, '#define __%s__' % cm, '']
        for acc, nm, ds, cv in fields:
            if acc & 0x18 == 0x18 and cv and cv[0] in ('int', 'long') and ds in 'ZBCSIJ':
                if cv[0] == 'int':
                    L.append('#undef %s_%s' % (cm, nm))
                    L.append('#define %s_%s %dL' % (cm, nm, struct.unpack('>i', cv[1])[0]))
                else:
                    L.append('#undef %s_%s' % (cm, nm))
                    L.append('#define %s_%s %dLL' % (cm, nm, struct.unpack('>q', cv[1])[0]))
        L += ['#ifdef __cplusplus', 'extern "C"', '{', '#endif', '']
        nat = [m for m in methods if m[0] & 0x100]
        names = [m[1] for m in nat]
        for acc, nm, ds, _ in nat:
            al, rt = args(ds)
            fn = 'Java_%s_%s' % (cm, mangle(nm))
            if names.count(nm) > 1:
                fn += '__' + mangle(ds[1:ds.index(')')])
            ps = ['JNIEnv *env', 'jclass' if acc & 8 else 'jobject'] + [ctype(t) for t in al]
            L.append('JNIEXPORT %s JNICALL %s (%s);' % (ctype(rt), fn, ', '.join(ps)))
        L += ['', '#ifdef __cplusplus', '}', '#endif', '', '#endif /* __%s__ */' % cm, '']
        target = out or (cm + '.h')
        open(target, 'w').write('\n'.join(L))

main()
