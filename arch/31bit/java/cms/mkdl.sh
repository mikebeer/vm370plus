#!/bin/sh
# mkdl.sh OBJ... > cmsdl.c -- the dlopen/dlsym table for JamVM on CMS: every
# Java_* and JNI_OnLoad symbol defined in the native objects.  dlopen of any
# lib*.so name succeeds; dlsym ignores the handle.  VM/370plus 9.35.
syms=$(s390x-linux-gnu-nm -g --defined-only "$@" | awk '$2=="T" && ($3 ~ /^Java_/ || $3=="JNI_OnLoad") {print $3}' | sort -u)
echo '/* generated by mkdl.sh */'
echo '#include <string.h>'
echo '#include <stdio.h>'
for s in $syms; do echo "extern char $s[];"; done
echo 'static const struct { const char *n; void *a; } tab[] = {'
for s in $syms; do echo "  { \"$s\", $s },"; done
echo '  { 0, 0 } };'
cat <<'C'
static char err[300];
void *dlopen(const char *p, int f)
{
    const char *b = p ? strrchr(p, '/') : 0;
    b = b ? b + 1 : p;
    if (!b || strncmp(b, "lib", 3) || !strstr(b, ".so")) {
        snprintf(err, sizeof err, "%s: no such native library", p ? p : "(null)");
        return 0;
    }
    return (void *)tab;
}
void *dlsym(void *h, const char *s)
{
    int lo = 0, hi = sizeof tab / sizeof tab[0] - 2;
    while (lo <= hi) {
        int m = (lo + hi) / 2, c = strcmp(s, tab[m].n);
        if (!c) return tab[m].a;
        if (c < 0) hi = m - 1; else lo = m + 1;
    }
    snprintf(err, sizeof err, "%s: undefined symbol", s);
    return 0;
}
int dlclose(void *h) { return 0; }
char *dlerror(void) { return err[0] ? err : 0; }
C
